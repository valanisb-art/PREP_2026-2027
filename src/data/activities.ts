export function getActivityAlerts(today: Date = new Date()) {
  const alerts: { activity: Activity; type: 'proxima' | 'activa' | 'vencida' | 'critica'; daysInfo: number }[] = [];
  activities.forEach((a) => {
    if (a.status === 'Entregado') return;
    const inicio = new Date(a.proyeccion.inicio);
    const termino = new Date(a.proyeccion.termino);
    const diffInicio = Math.ceil((inicio.getTime() - today.getTime()) / (1000 * 60 * 60 * 24));
    const diffTermino = Math.ceil((termino.getTime() - today.getTime()) / (1000 * 60 * 60 * 24));
    if (a.situacionCritica && a.situacionCritica.trim() !== '') {
      alerts.push({ activity: a, type: 'critica', daysInfo: diffTermino });
    }
    if (diffTermino < 0) {
      alerts.push({ activity: a, type: 'vencida', daysInfo: Math.abs(diffTermino) });
    } else if (diffInicio <= 0 && diffTermino >= 0) {
      alerts.push({ activity: a, type: 'activa', daysInfo: diffTermino });
    } else if (diffInicio > 0 && diffInicio <= 30) {
      alerts.push({ activity: a, type: 'proxima', daysInfo: diffInicio });
    }
  });
  return alerts.sort((a, b) => a.daysInfo - b.daysInfo);
}

export function getStats() {
  let pendiente = 0, enProceso = 0, entregado = 0;
  activities.forEach((a) => {
    if (a.status === 'Pendiente') pendiente++;
    else if (a.status === 'En Proceso') enProceso++;
    else entregado++;
  });
  return { total: activities.length, pendiente, enProceso, entregado };
}